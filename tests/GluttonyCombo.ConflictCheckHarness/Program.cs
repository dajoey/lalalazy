    private static int _pass;
    private static int _fail;

    private static int Main()
    {
        var t0 = DateTime.UnixEpoch.AddSeconds(IncidentEpochs[0]);

        // ---------------------------------------------------------------------------
        // 1. The incident, characterized. The pre-fix path logged one WRN per throw
        //    with no throttle, so all 359 failures became 359 identical lines.
        // ---------------------------------------------------------------------------
        Check("incident data holds all 359 measured failures",
            IncidentEpochs.Length == 359, IncidentEpochs.Length.ToString());
        Check("incident spans about eight and three-quarter hours",
            IncidentEpochs[^1] - IncidentEpochs[0] > 31000 &&
            IncidentEpochs[^1] - IncidentEpochs[0] < 32000,
            (IncidentEpochs[^1] - IncidentEpochs[0]).ToString("0"));

        // ---------------------------------------------------------------------------
        // 2. The fix contract. The same 359 failures through the shipped gate must
        //    collapse to about one line per 15-minute window, with every dropped line
        //    accounted for in the suppressed counts.
        // ---------------------------------------------------------------------------
        var gate = new LogEmitGate(ShippedWindow, ShippedBurst);
        var emitted = 0;
        var suppressedTotal = 0;
        var notesSeen = 0;
        foreach (var epoch in IncidentEpochs)
        {
            var now = DateTime.UnixEpoch.AddSeconds(epoch);
            if (gate.ShouldEmit(FailureLine, now, out var suppressed))
            {
                emitted++;
                suppressedTotal += suppressed;
                if (!string.IsNullOrEmpty(gate.SuppressedNote(suppressed)))
                    notesSeen++;
            }
        }

        var dropped = IncidentEpochs.Length - emitted;

        // ---------------------------------------------------------------------------
        // 3. Flush. The gate reports a window's drops on the next emit, so one quiet-
        //    hour-later failure both proves the gate re-opens and carries the tail.
        // ---------------------------------------------------------------------------
        var after = DateTime.UnixEpoch.AddSeconds(IncidentEpochs[^1] + 3600);
        var flushEmitted = gate.ShouldEmit(FailureLine, after, out var flushSuppressed);
        Check("isolated failure after a quiet hour emits at once",
            flushEmitted, flushSuppressed.ToString());
        suppressedTotal += flushSuppressed;

        Check("gated replay emits at most 36 lines, not 359", emitted <= 36, emitted.ToString());
        Check("gated replay still emits (the signal survives)", emitted >= 1, emitted.ToString());
        Check("every dropped line is counted in a suppressed total",
            suppressedTotal == dropped, $"{suppressedTotal} vs {dropped}");
        Check("a rollover line carries the suppressed count",
            notesSeen >= 1, notesSeen.ToString());

        Console.WriteLine($"PASS={_pass} FAIL={_fail} " +
            $"({_pass + _fail} cases, incident replayed from {t0:HH:mm} UTC, " +
            $"{emitted} emitted / {dropped} suppressed)");
        Console.WriteLine(_fail == 0 ? "OK" : "FAIL");
        return _fail == 0 ? 0 : 1;
    }

    private static void Check(string name, bool ok, string detail)
    {
        if (ok)
        {
            _pass++;
            Console.WriteLine($"PASS: {name}");
        }
        else
        {
            _fail++;
            Console.WriteLine($"FAIL: {name} [{detail}]");
        }
    }
